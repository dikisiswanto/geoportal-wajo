function normalizeAdminName(value) {
  return String(value ?? "")
    .normalize("NFKC")
    .replace(/[^\p{L}\p{N}]+/gu, "")
    .toLowerCase();
}

function normalizeAlias(value) {
  return normalizeAdminName(value);
}

function canonicalBpsVillageName(value) {
  const normalized = normalizeAlias(value);
  return ALIASES.get(normalized) || String(value ?? "").trim();
}

function getWajoKecamatanByKemendagri(code) {
  const normalized = String(code ?? "").replace(/[^0-9.]/g, "");
  return WAJO_ADMIN_MASTER.kecamatan.find((item) => item.codeKemendagri === normalized) || null;
}

function getWajoKecamatanByBps(code) {
  return WAJO_ADMIN_MASTER.kecamatan.find((item) => item.codeBps === String(code ?? "").trim()) || null;
}

function normalizeKemendagriVillageCode(code) {
  const raw = String(code ?? "").trim();
  if (!raw) return null;

  const dotted = raw.replace(/-/g, ".");
  const parts = dotted.split(".").filter(Boolean);
  if (parts.length === 4 && parts.every((part) => /^\d+$/.test(part))) {
    return parts.map((part, index) => part.padStart(index === 0 ? 2 : index === 3 ? 4 : 2, "0")).join(".");
  }

  const digits = raw.replace(/\D/g, "");
  if (digits.length === 10) {
    return `${digits.slice(0, 2)}.${digits.slice(2, 4)}.${digits.slice(4, 6)}.${digits.slice(6, 10)}`;
  }
  return null;
}

function getWajoVillageByKemendagriCode(code, villageName = null) {
  const normalized = normalizeKemendagriVillageCode(code);
  if (!normalized) return null;

  const parts = normalized.split(".");
  const kec = getWajoKecamatanByKemendagri(parts.slice(0, 3).join("."));
  if (!kec) return null;

  const localCode = parts[3];
  const shortCode = localCode.slice(-3);
  let nameBps = null;
  let localBpsCode = null;

  // Kode BIG/Kemendagri adalah identitas wilayah dan menentukan kecamatan/lokasi.
  // Nomor lokal BIG tidak boleh dipakai untuk menebak kode BPS karena urutannya
  // dapat berbeda. Bila nama sumber tersedia, cari padanan BPS hanya di kecamatan
  // yang sudah ditentukan oleh kode BIG.
  if (villageName) {
    const byName = getWajoVillageByKemendagri(kec.codeKemendagri, villageName);
    if (byName) {
      nameBps = byName.nameBps;
      localBpsCode = byName.localBpsCode;
    }
  } else {
    nameBps = kec.desa[shortCode] || null;
    localBpsCode = nameBps ? shortCode : null;
  }

  return {
    kecamatan: kec,
    codeKemendagri: normalized,
    codeBps: localBpsCode ? `${kec.codeBps}${localBpsCode}` : null,
    nameBps,
    nameKemendagri: null,
    localBpsCode,
  };
}

function getWajoVillageByKemendagri(kecCode, villageName) {
  const kec = getWajoKecamatanByKemendagri(kecCode);
  if (!kec) return null;
  const normalized = normalizeAdminName(canonicalBpsVillageName(villageName));
  for (const [localCode, name] of Object.entries(kec.desa)) {
    if (normalizeAdminName(name) === normalized) {
      return {
        kecamatan: kec,
        codeKemendagri: null,
        codeBps: `${kec.codeBps}${localCode}`,
        nameBps: name,
        localBpsCode: localCode,
      };
    }
  }
  return null;
}

